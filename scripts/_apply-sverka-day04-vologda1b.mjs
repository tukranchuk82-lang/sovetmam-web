const short = (v) => {
  const s = typeof v === "object" ? JSON.stringify(v) : String(v);
  return s.length > 110 ? s.slice(0, 110) + "…" : s;
};

let changes = 0,
  ok = 0,
  fail = 0;

for (const [slug, fields] of Object.entries(edits)) {
  const c = cur[slug];
  if (!c) {
    console.log("!! НЕТ В БЭКАПЕ:", slug);
    fail++;
    continue;
  }
  console.log(`\n# ${slug} — ${c.title}`);
  for (const [f, v] of Object.entries(fields)) {
    const before = short(c[f]);
    const after = short(v);
    if (before === after) {
      console.log(`  = ${f}: без изменений`);
      continue;
    }
    console.log(`  · ${f}:`);
    console.log(`      было:  ${before}`);
    console.log(`      стало: ${after}`);
    changes++;
  }
  if (APPLY) {
    const { error } = await sb.from("measures").update(fields).eq("slug", slug);
    if (error) {
      console.log("  ОШИБКА:", error.message);
      fail++;
    } else ok++;
  }
}

console.log(
  `\n${APPLY ? "ЗАПИСАНО" : "СУХОЙ ПРОГОН"}: мер ${Object.keys(edits).length}, изменений полей ${changes}` +
    (APPLY ? `, успешно ${ok}, ошибок ${fail}` : ""),
);
