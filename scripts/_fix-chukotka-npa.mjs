const APPLY = process.argv.includes("--apply");

if (!APPLY) {
  console.log(`Сухой прогон: ${patches.length} правки (Чукотка, по текстам НПА)\n`);
  for (const p of patches) {
    console.log(`  ${p.slug}`);
    if (p.title) console.log(`    title:    ${p.title}`);
    if (p.amount) console.log(`    amount:   ${p.amount}`);
    if (p.criteria) console.log(`    criteria: ${JSON.stringify(p.criteria)}`);
    console.log("");
  }
  console.log("Для записи: node scripts/_fix-chukotka-npa.mjs --apply");
  process.exit(0);
}

mkdirSync("verification", { recursive: true });
const { data: before } = await sb
  .from("measures")
  .select("*")
  .in("slug", patches.map((p) => p.slug));
writeFileSync("verification/backup-chukotka-npa.json", JSON.stringify(before, null, 2), "utf8");
console.log(`бэкап: verification/backup-chukotka-npa.json (${(before || []).length} мер)\n`);

let ok = 0;
let fail = 0;
for (const p of patches) {
  const { slug, ...fields } = p;
  const { error } = await sb
    .from("measures")
    .update({
      ...fields,
      updated_at_label: "2026",
      verified_at: "2026-07-26T18:00:00+03:00",
      verified_by: "sverka",
    })
    .eq("slug", slug);
  if (error) {
    console.log("FAIL", slug, "-", error.message);
    fail++;
  } else {
    console.log("OK  ", slug);
    ok++;
  }
}

console.log(`\nDONE: ${ok} правок, ${fail} ошибок`);
