const slugs = Object.keys(PATCHES);
const { data: before, error } = await sb
  .from("measures")
  .select("slug,title,amount,eligibility,how_to_apply,documents,tips,criteria,deadline,source_name,source_url")
  .in("slug", slugs);
if (error) throw error;
if (before.length !== slugs.length) {
  const found = before.map((m) => m.slug);
  throw new Error("не нашлись: " + slugs.filter((s) => !found.includes(s)).join(", "));
}

for (const m of before) {
  const p = PATCHES[m.slug];
  console.log(`\n${m.title}`);
  console.log(`  как оформить: ${(m.how_to_apply ?? []).length} → ${p.how_to_apply.length}`);
  console.log(`  документы:    ${(m.documents ?? []).length} → ${p.documents.length}`);
  console.log(`  важно знать:  ${(m.tips ?? []).length} → ${p.tips.length}`);
  console.log(`  кому положено: ${m.eligibility ? "было" : "не было"} → ${p.eligibility.split("\n").length} абз.`);
  console.log(`  условия: ${JSON.stringify(m.criteria).slice(0, 90)} · срок: ${m.deadline ? "есть" : "нет"}`);
}

if (!APPLY) {
  console.log("\nСухой прогон. Для записи: node scripts/_fill-core-9.mjs --apply");
  process.exit(0);
}

writeFileSync("scripts/_backup-core-9.json", JSON.stringify(before, null, 1), "utf8");
for (const slug of slugs) {
  const { error: e } = await sb.from("measures").update(PATCHES[slug]).eq("slug", slug);
  if (e) throw new Error(`${slug}: ${e.message}`);
  console.log("записано:", slug);
}
