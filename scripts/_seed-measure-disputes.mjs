const client = new pg.Client({ connectionString: dbUrl });
await client.connect();

for (const d of DISPUTES) {
  const { rows } = await client.query(
    "select 1 from measure_disputes where measure_slug = $1 and title = $2",
    [d.measureSlug, d.title],
  );
  if (rows.length > 0) {
    console.log(`SKIP (уже есть): ${d.title}`);
    continue;
  }
  await client.query(
    "insert into measure_disputes (measure_slug, title, reason, sources) values ($1, $2, $3, $4::jsonb)",
    [d.measureSlug, d.title, d.reason, JSON.stringify(d.sources)],
  );
  console.log(`OK: ${d.title}`);
}

await client.end();
