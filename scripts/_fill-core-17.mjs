const slugs = Object.keys(PATCHES);
const { data: before, error } = await sb
  .from("measures").select("slug,title,eligibility,how_to_apply,documents,tips,criteria").in("slug", slugs);
if (error) throw error;
if (before.length !== slugs.length) {
  const found = before.map((m) => m.slug);
  throw new Error("не нашлись: " + slugs.filter((s) => !found.includes(s)).join(", "));
}
for (const m of before) {
  const p = PATCHES[m.slug];
  console.log(`${m.title.slice(0, 42).padEnd(44)} шаги ${(m.how_to_apply ?? []).length}→${p.how_to_apply.length} · док ${(m.documents ?? []).length}→${p.documents.length} · важно ${(m.tips ?? []).length}→${p.tips.length}`);
}
if (!APPLY) { console.log("\nСухой прогон. Для записи: --apply"); process.exit(0); }
writeFileSync("scripts/_backup-core-17.json", JSON.stringify(before, null, 1), "utf8");
for (const slug of slugs) {
  const { error: e } = await sb.from("measures").update(PATCHES[slug]).eq("slug", slug);
  if (e) throw new Error(`${slug}: ${e.message}`);
}
console.log("\nзаписано:", slugs.length, "мер");
