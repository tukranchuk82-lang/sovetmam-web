  fail = 0,
  skip = 0;

for (const m of measures) {
  const { data: exists } = await sb.from("measures").select("slug").eq("slug", m.slug).maybeSingle();
  if (exists) {
    console.log(`= ${m.slug} уже есть — пропускаю`);
    skip++;
    continue;
  }

  const row = {
    slug: m.slug,
    title: m.title,
    short_description: m.short_description,
    level: "regional",
    region: m.region,
    category: m.category,
    amount: m.amount,
    segments: m.segments,
    criteria: m.criteria,
    how_to_apply: m.how_to_apply,
    documents: m.documents,
    tips: m.tips,
    source_name: SRC[m.region].source_name,
    source_url: SRC[m.region].source_url,
    updated_at_label: "2026",
    is_published: m.is_published !== false,
    sort_order: 0,
  };

  console.log(
    `+ ${m.slug} — ${m.title}` + (row.is_published ? "" : "  [добавляется СКРЫТОЙ]"),
  );
  if (APPLY) {
    const { error } = await sb.from("measures").insert(row);
    if (error) {
      console.log("  ОШИБКА:", error.message);
      fail++;
    } else ok++;
  }
}

console.log(
  `\n${APPLY ? "ЗАПИСАНО" : "СУХОЙ ПРОГОН"}: мер к добавлению ${measures.length}` +
    (APPLY ? `, добавлено ${ok}, пропущено ${skip}, ошибок ${fail}` : ""),
);
