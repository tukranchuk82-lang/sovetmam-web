mkdirSync("verification", { recursive: true });
const { data: before } = await sb
  .from("measures")
  .select("*")
  .in("slug", patches.map((p) => p.slug));
writeFileSync("verification/backup-chuvashia-npa.json", JSON.stringify(before, null, 2), "utf8");
console.log(`бэкап: verification/backup-chuvashia-npa.json (${(before || []).length} мер)\n`);

let ok = 0;
let fail = 0;
for (const p of patches) {
  const { slug, ...fields } = p;
  const { error } = await sb
    .from("measures")
    .update({
      ...fields,
      updated_at_label: "2026",
      verified_at: "2026-07-26T18:00:00+03:00",
      verified_by: "sverka",
    })
    .eq("slug", slug);
  if (error) {
    console.log("FAIL", slug, "-", error.message);
    fail++;
  } else {
    console.log("OK  ", slug);
    ok++;
  }
}

console.log(`\nDONE: ${ok} правок, ${fail} ошибок`);
