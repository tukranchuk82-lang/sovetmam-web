import type { MetadataRoute } from "next";
import { siteUrl } from "@/lib/site";

/**
 * robots.txt — что поисковику можно смотреть, а что нет.
 *
 * Открыто всё, ради чего человек и приходит из поиска: главная, каталог мер,
 * тематические и ситуационные разделы, пирамида, страница об организации.
 *
 * Закрыт личный кабинет и всё, что за ним: там нет ничего полезного для поиска,
 * зато есть переписка и личные данные. Закрыты и служебные адреса — форма
 * ответа по одноразовой ссылке из письма, переход из бота, API. Страницу входа
 * тоже прячем: в выдаче она бесполезна и только оттягивает на себя запросы,
 * по которым человек должен попадать на главную.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: "*",
      allow: "/",
      disallow: [
        "/admin",
        "/profile",
        "/saved",
        "/login",
        "/connect",
        "/otvet",
        "/iz-bota",
        "/api/",
      ],
    },
    sitemap: `${siteUrl()}/sitemap.xml`,
    // Подсказка Яндексу, какой адрес считать основным.
    host: siteUrl(),
  };
}
