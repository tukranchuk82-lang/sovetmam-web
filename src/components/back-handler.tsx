"use client";

import { useEffect, useRef } from "react";

/**
 * Кнопка «Назад» в шапке: экран может перехватить её на себя.
 *
 * Многошаговые экраны (анкета подбора) живут в состоянии страницы, а не в
 * истории браузера: шаг — это не адрес. Из-за этого «Назад» уводил человека со
 * страницы целиком — заполнял анкету, нажал «Назад» и оказался на главной, а
 * всё введённое пропало.
 *
 * Экран регистрирует свой обработчик: вернул `true` — значит шаг назад сделан
 * внутри экрана, уходить со страницы не нужно; вернул `false` — шапка
 * отрабатывает как обычно, историей браузера.
 *
 * Реестр — одна переменная модуля, а не контекст: каркас приложения в дереве
 * один, обработчик тоже всегда один (последний смонтированный экран), а
 * мутация ref-а из контекста ломала бы правила React Compiler.
 */
type BackHandler = () => boolean;

let currentHandler: BackHandler | null = null;

/** Ставит обработчик и возвращает функцию снятия. Зовётся только из эффекта. */
function registerBackHandler(handler: BackHandler): () => void {
  currentHandler = handler;
  return () => {
    // Снимаем только свой: другой экран мог успеть встать раньше нас.
    if (currentHandler === handler) currentHandler = null;
  };
}

/** Шапка приложения: отдал ли экран шаг назад себе. */
export function runBackHandler(): boolean {
  return currentHandler ? currentHandler() : false;
}

/**
 * Регистрирует обработчик «Назад» на время жизни экрана.
 *
 * Замыкание обработчика меняется на каждый рендер (в нём номер шага), поэтому
 * в реестр кладём стабильную обёртку, а свежую версию держим в ref и обновляем
 * эффектом — иначе шапка звала бы устаревшую.
 */
export function useBackHandler(handler: BackHandler): void {
  const latest = useRef(handler);

  useEffect(() => {
    latest.current = handler;
  });

  useEffect(() => registerBackHandler(() => latest.current()), []);
}
