/**
 * Разметка Schema.org — «паспорт» страницы для поисковика.
 *
 * Обычный текст робот читает как текст и догадывается о смысле сам. Разметка
 * говорит прямо: это организация, вот её сайт; это мера господдержки, вот её
 * сумма и кто её выдаёт. Из такой разметки собирают расширенные результаты —
 * те самые карточки с крошками и описанием под ссылкой.
 *
 * Отдаётся тегом <script type="application/ld+json"> — он ничего не рисует и
 * виден только роботам.
 */

export function JsonLd({ data }: { data: Record<string, unknown> }) {
  return (
    <script
      type="application/ld+json"
      // Данные наши собственные, из базы мер. JSON.stringify экранирует
      // кавычки; закрывающий тег внутри строки заменяем, чтобы строка из базы
      // не могла оборвать скрипт.
      dangerouslySetInnerHTML={{
        __html: JSON.stringify(data).replace(/</g, "\\u003c"),
      }}
    />
  );
}
