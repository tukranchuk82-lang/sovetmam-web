/**
 * Название региона в дательном падеже — для заголовков вида «Сводка по
 * Алтайскому краю». В списке REGIONS названия стоят в именительном, и подставлять
 * их в такую фразу как есть нельзя.
 *
 * Правил немного, потому что названия устроены однотипно: прилагательное +
 * «область / край / округ / Республика», «Республика + имя» и три города.
 * Часть после тире («— Югра», «— Кузбасс», «— Алания») и скобки не склоняем.
 */
const NOUNS: Record<string, string> = {
  область: "области",
  Республика: "Республике",
  край: "краю",
  округ: "округу",
  Москва: "Москве",
  Севастополь: "Севастополю",
  "Санкт-Петербург": "Санкт-Петербургу",
};

function declineWord(w: string): string {
  if (NOUNS[w]) return NOUNS[w];
  if (/ая$/.test(w)) return w.replace(/ая$/, "ой");
  if (/(ий|ый)$/.test(w)) return w.replace(/(ий|ый)$/, "ому");
  return w;
}

export function regionDative(region: string): string {
  const [main, ...tail] = region.split(" — ");
  const words = main.split(" ");
  // «Республика Татарстан», «Республика Саха (Якутия)»: склоняется только первое слово.
  const out =
    words[0] === "Республика"
      ? ["Республике", ...words.slice(1)]
      : words.map(declineWord);
  return [out.join(" "), ...tail].join(" — ");
}
