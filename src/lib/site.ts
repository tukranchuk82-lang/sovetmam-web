/**
 * Сведения о сайте: адрес, название, описание.
 *
 * Нужны в трёх местах сразу — в ссылках писем, в мета-тегах для поисковиков и
 * в карточке для мессенджеров. Держим их одним набором, чтобы адрес не
 * приходилось править в четырёх файлах.
 */

/**
 * Базовый адрес приложения.
 *
 * Next о своём домене не знает, а поисковику и письму нужна абсолютная ссылка —
 * берём из переменной окружения, иначе боевой адрес по умолчанию.
 *
 * Сначала смотрим APP_URL и только потом NEXT_PUBLIC_APP_URL. Переменные с
 * префиксом NEXT_PUBLIC_ Next подставляет в код на сборке, поэтому в Coolify их
 * пришлось бы помечать как build-переменную и пересобирать образ. Ссылки в
 * письмах и мета-теги строит сервер — обычной серверной переменной достаточно,
 * и она подхватывается простым перезапуском.
 */
export function siteUrl(): string {
  const raw =
    process.env.APP_URL ??
    process.env.NEXT_PUBLIC_APP_URL ??
    "https://app.sovetmam.ru";
  return raw.replace(/\/+$/, "");
}

/** Полный адрес страницы из пути внутри приложения. */
export function absoluteUrl(path: string): string {
  return `${siteUrl()}${path.startsWith("/") ? path : `/${path}`}`;
}

