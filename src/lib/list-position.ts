"use client";

import { useCallback, useEffect, useRef } from "react";

/**
 * Возвращение в длинный список на то же место.
 *
 * Список выдаётся порциями по кнопке «Показать ещё», и это состояние живёт
 * только в памяти страницы. Человек раскрывал список пять раз, уходил читать
 * меру, возвращался «назад» — и оказывался в начале, с первой порцией мер.
 * Приходилось нажимать «Показать ещё» столько же раз заново (правка заказчика
 * 17.08.2026).
 *
 * Само место прокрутки возвращает AppShell: прокрутка живёт в <main>, он ведёт
 * список позиций по адресам и удерживает нужную позицию несколько кадров после
 * «назад». Именно этих кадров нам и хватает: как только список раскроется на
 * прежнюю длину, страница станет прежней высоты и удерживаемая позиция
 * наконец совпадёт. До правки удерживать было нечего — короткая страница
 * упиралась в свой конец, и человек оказывался ровно там, где нажал «Ещё».
 * Поэтому здесь только состояние списка, без прокрутки: два механизма на одну
 * прокрутку дрались бы между собой.
 *
 * Состояние храним в записи истории браузера (history.state), а не в
 * sessionStorage. Разница важна: запись истории — это конкретный шаг «назад»,
 * поэтому возврат восстанавливает список, а свежий заход в тот же раздел с
 * главной начинается с чистого листа. С хранилищем пришлось бы угадывать,
 * вернулся человек или пришёл впервые, и в половине случаев мы бросали бы его
 * посреди списка без причины.
 *
 * Next.js разрешает работать с history напрямую и сам подмешивает в state свои
 * служебные поля, так что чужое ничего не ломает (docs: Getting Started →
 * Linking and Navigating → Native History API).
 */

const FIELD = "listPosition";

export function useListPosition<S extends object>(apply: (saved: S) => void) {
  // Функция apply создаётся заново на каждой отрисовке, и в зависимостях
  // эффекта ей не место — восстановление должно случиться ровно один раз.
  // Держим ту, что пришла первой: внутри она только раскладывает сохранённое по
  // setState, а те не меняются.
  const applyRef = useRef(apply);

  useEffect(() => {
    const state = window.history.state as Record<string, unknown> | null;
    const saved = state?.[FIELD] as S | undefined;
    if (saved) applyRef.current(saved);
  }, []);

  /** Запомнить состояние списка перед уходом с экрана. */
  return useCallback((state: S) => {
    const prev = (window.history.state as Record<string, unknown> | null) ?? {};
    window.history.replaceState({ ...prev, [FIELD]: state }, "");
  }, []);
}
