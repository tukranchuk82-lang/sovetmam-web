-- Отметка «человек уже видел напоминание подключить мессенджер».
--
-- Раньше подключение мессенджера было обязательным шагом сразу после
-- регистрации. Теперь это ненавязчивое напоминание в личном кабинете:
-- через 15 секунд после входа на аватарке в шапке загорается кружочек,
-- а открыв кабинет, человек видит блок «Мессенджеры». Открыл кабинет —
-- напоминание считается прочитанным и больше не появляется.
alter table app_users
  add column if not exists messenger_hint_seen_at timestamptz;
