-- 0023_applies_by_child.sql
-- Меры, которые ребёнок оформляет на себя сам: Пушкинская карта,
-- образовательный кредит.
--
-- Родителю их видеть нужно — обычно именно он о них узнаёт первым и помогает
-- оформить, — но в общий список подборки они не попадают: сделать по ним
-- родитель ничего не может. Поэтому в подборке они уходят отдельным блоком
-- «Положено вашему ребёнку» в самый конец.

alter table public.measures
  add column if not exists applies_by_child boolean not null default false;

comment on column public.measures.applies_by_child is
  'Заявление подаёт сам ребёнок; в подборке родителя — отдельным блоком в конце.';
