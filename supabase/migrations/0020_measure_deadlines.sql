-- Срок подачи заявления у меры.
--
-- Книга Буцкой держится на сроках: 12 недель беременности открывают единое
-- пособие, шесть месяцев на единовременное пособие при рождении — иначе
-- деньги сгорают безвозвратно, семейная налоговая выплата принимается только
-- с 1 июня по 1 октября. У нас же не было ни одного поля со сроком, и
-- предупредить человека мы не могли.
--
-- Храним разбором, а не текстом, чтобы считать остаток дней для конкретной
-- семьи: «осталось 40 дней» человек воспринимает иначе, чем «в течение шести
-- месяцев». Форма записи описана в MeasureDeadline (src/lib/measures.ts).
alter table measures add column if not exists deadline jsonb;

comment on column measures.deadline is
  'Срок подачи: {kind, ...параметры, note}. Разбор в src/lib/measures.ts';
